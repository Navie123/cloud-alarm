// Get current language from localStorage or default to English
function getCurrentLanguage() {
  return localStorage.getItem('language') || 'en';
}

// Set language
function setLanguage(lang) {
  localStorage.setItem('language', lang);
  applyTranslations(lang);
}

// Get translation
function t(key) {
  const lang = getCurrentLanguage();
  return translations[lang][key] || translations.en[key] || key;
}

// Apply translations to the page
function applyTranslations(lang) {
  const trans = translations[lang] || translations.en;
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (trans[key]) {
      if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
        el.placeholder = trans[key];
      } else {
        el.textContent = trans[key];
      }
    }
  });
  
  // Update sidebar sections
  updateSidebarTranslations(trans);
  
  // Update sensor cards
  updateSensorTranslations(trans);
  
  // Update quick stats
  updateQuickStatsTranslations(trans);
  
  // Update language toggle buttons
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.remove('active');
  });
  document.getElementById(`lang-${lang}`)?.classList.add('active');
  
  // Trigger custom event for dynamic content updates
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function updateSidebarTranslations(trans) {
  // Sidebar title
  const sidebarTitle = document.querySelector('.sidebar-title');
  if (sidebarTitle) sidebarTitle.textContent = trans.sidebarTitle;
  
  // Section titles
  const sections = document.querySelectorAll('.sidebar-section-title');
  sections.forEach(section => {
    const icon = section.querySelector('i');
    const text = section.textContent.trim();
    if (text.includes('APPEARANCE') || text.includes('HITSURA')) {
      section.innerHTML = icon.outerHTML + ' ' + trans.sidebarAppearance;
    } else if (text.includes('LANGUAGE') || text.includes('WIKA')) {
      section.innerHTML = icon.outerHTML + ' ' + trans.sidebarLanguage;
    } else if (text.includes('ALARM CONTROLS') || text.includes('KONTROL')) {
      section.innerHTML = icon.outerHTML + ' ' + trans.sidebarAlarmControls;
    } else if (text.includes('SYSTEM INFO') || text.includes('IMPORMASYON')) {
      section.innerHTML = icon.outerHTML + ' ' + trans.sidebarSystemInfo;
    } else if (text.includes('HOUSEHOLD') || text.includes('SAMBAHAYAN')) {
      section.innerHTML = icon.outerHTML + ' ' + trans.sidebarHousehold;
    }
  });
  
  // Theme options
  const darkTheme = document.querySelector('#darkThemeOption span');
  const lightTheme = document.querySelector('#lightThemeOption span');
  if (darkTheme) darkTheme.textContent = trans.sidebarThemeDark;
  if (lightTheme) lightTheme.textContent = trans.sidebarThemeLight;
  
  // Language options
  const engLang = document.querySelector('#lang-en span');
  const filLang = document.querySelector('#lang-tl span');
  if (engLang) engLang.textContent = trans.sidebarLangEnglish;
  if (filLang) filLang.textContent = trans.sidebarLangFilipino;
  
  // Buttons
  const silenceBtn = document.getElementById('silenceAlarmSideBtn');
  if (silenceBtn) {
    const icon = silenceBtn.querySelector('i').outerHTML;
    silenceBtn.innerHTML = icon + ' ' + trans.sidebarSilenceAlarm;
  }
  
  const logoutBtn = document.querySelector('.sidebar-section button[onclick="logout()"]');
  if (logoutBtn) {
    const icon = logoutBtn.querySelector('i').outerHTML;
    logoutBtn.innerHTML = icon + ' ' + trans.sidebarLogout;
  }
}

function updateSensorTranslations(trans) {
  // Sensor card headers
  const sensorHeaders = {
    'gas-card': trans.sensorGas,
    'smoke-card': trans.sensorSmoke,
    'co-card': trans.sensorCO,
    'aqi-card': trans.sensorAQI,
    'temp-card': trans.sensorTemp,
    'humidity-card': trans.sensorHumidity
  };
  
  Object.keys(sensorHeaders).forEach(cardClass => {
    const card = document.querySelector(`.${cardClass}`);
    if (card) {
      const header = card.querySelector('.sensor-header span');
      if (header) header.textContent = sensorHeaders[cardClass];
    }
  });
  
  // Sensor status labels
  document.querySelectorAll('.status-label').forEach(label => {
    const text = label.textContent.trim();
    if (text.includes('Threshold') || text.includes('Hangganan')) {
      label.textContent = trans.statusThreshold + ':';
    } else if (text.includes('Status') || text.includes('Kalagayan')) {
      label.textContent = trans.statusStatus + ':';
    } else if (text.includes('Level') || text.includes('Antas')) {
      label.textContent = trans.statusLevel + ':';
    }
  });
}

function updateQuickStatsTranslations(trans) {
  const stats = document.querySelectorAll('.stat-label');
  stats.forEach(stat => {
    const text = stat.textContent.trim();
    if (text.includes('Voltage') || text.includes('Boltahe')) {
      stat.textContent = trans.statVoltage;
    } else if (text.includes('Total Alarms') || text.includes('Kabuuang')) {
      stat.textContent = trans.statAlarms;
    } else if (text.includes('Device Status') || text.includes('Kalagayan')) {
      stat.textContent = trans.statDevice;
    } else if (text.includes('Last Update') || text.includes('Huling')) {
      stat.textContent = trans.statLastUpdate;
    }
  });
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
  const currentLang = getCurrentLanguage();
  applyTranslations(currentLang);
});
